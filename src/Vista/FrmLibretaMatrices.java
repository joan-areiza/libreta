    private void btn_libretaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_libretaActionPerformed
        // TODO add your handling code here:
        txtRta.append("LA ESCUELITA DE DOÑA RITA CON MATRICES");
        txtRta.append("\nNombres: "+ObjCL.getNombres()+" Apellidos: "+ObjCL.getApellidos());
        txtRta.append("\nGrado: "+ObjCL.getGrado()+" Director de grupo: "+ObjCL.getDirector());
        /*
        
     __  __      _      _____   ____    ___    ____   _____   ____  
    |  \/  |    / \    |_   _| |  _ \  |_ _|  / ___| | ____| / ___| 
    | |\/| |   / _ \     | |   | |_) |  | |  | |     |  _|   \___ \ 
    | |  | |  / ___ \    | |   |  _ <   | |  | |___  | |___   ___) |
    |_|  |_| /_/   \_\   |_|   |_| \_\ |___|  \____| |_____| |____/ 

    */
        
        
        
         //LIMPIEZA MATRIZ TEXTO
        for (ObjCLV.i = 0; ObjCLV.i < 50; ObjCLV.i++) {
            for (ObjCLV.j = 0; ObjCLV.j < 1; ObjCLV.j++) { 
                ObjCLV.MT[ObjCLV.i][ObjCLV.j] = "";
            }
        }
        
         //LIMPIEZA MATRIZ REAL
        for (ObjCLV.i = 0; ObjCLV.i < 50; ObjCLV.i++) {
            for (ObjCLV.j = 0; ObjCLV.j < 6; ObjCLV.j++) { 
                ObjCLV.MR[ObjCLV.i][ObjCLV.j] = 0;
            }
        }
        

        ObjCLV.Cantidad = Integer.parseInt(JOptionPane.showInputDialog(null,"Cantidad de materias a procesar: ","DATOS DE LA LIBRETA",JOptionPane.INFORMATION_MESSAGE));
        for(ObjCLV.i=0;ObjCLV.i<=ObjCLV.Cantidad;ObjCLV.i++)
        {  //Entrada de datos
           
            ObjCLV.MT[ObjCLV.i][0] =  JOptionPane.showInputDialog(null,"Materia: ","PROCESANDO REGISTRO: "+String.valueOf(ObjCL.i),JOptionPane.INFORMATION_MESSAGE);
            
            ObjCLV.MR[ObjCLV.i][0] = Double.parseDouble(JOptionPane.showInputDialog(null,"Nota 1: ","PROCESANDO REGISTRO: "+String.valueOf(ObjCLV.i),JOptionPane.INFORMATION_MESSAGE));
            ObjCLV.MR[ObjCLV.i][2]  = Double.parseDouble(JOptionPane.showInputDialog(null,"Nota 2: ","PROCESANDO REGISTRO: "+String.valueOf(ObjCLV.i),JOptionPane.INFORMATION_MESSAGE));
            ObjCLV.MR[ObjCLV.i][4]  = Double.parseDouble(JOptionPane.showInputDialog(null,"Nota 3: ","PROCESANDO REGISTRO: "+String.valueOf(ObjCLV.i),JOptionPane.INFORMATION_MESSAGE));
            
            //Cálculos
            ObjCLV.MR[ObjCLV.i][1]  = ObjML.Calc30(ObjCLV.MR[ObjCLV.i][0]);
            ObjCLV.MR[ObjCLV.i][3]  = ObjML.Calc30(ObjCLV.MR[ObjCLV.i][2]);
            ObjCLV.MR[ObjCLV.i][5]  = ObjML.Calc40(ObjCLV.MR[ObjCLV.i][4]);
            
            ObjCLV.MR[ObjCLV.i][6]  = ObjML.CalcDef(ObjCLV.MR[ObjCLV.i][1] ,ObjCLV.MR[ObjCLV.i][3] ,ObjCLV.MR[ObjCLV.i][5] );
            
            
            if (ObjCLV.MR[ObjCLV.i][6] <3) ObjCLV.setPerdidas(ObjCLV.getPerdidas()+1);//Cuenta la materia perdida.
            ObjCLV.MT[ObjCLV.i][1] =ObjML.CalcMsjMateria(ObjCLV.MR[ObjCLV.i][6]);
            
        
            
            //Impresión de resultados
            txtRta.append("\nMateria: "+ObjCLV.MT[ObjCLV.i][0] );
            
            txtRta.append("\nNota 1: "+String.valueOf(ObjCLV.MR[ObjCLV.i][0]));
            txtRta.append("\n30 % nota 1: "+String.valueOf( ObjCLV.MR[ObjCLV.i][1]));
            
            txtRta.append("\nNota 2: "+String.valueOf( ObjCLV.MR[ObjCLV.i][2]));
            txtRta.append("\n30 % nota 2: "+String.valueOf( ObjCLV.MR[ObjCLV.i][3]));
            
            txtRta.append("\nNota 3: "+String.valueOf( ObjCLV.MR[ObjCLV.i][4]));
            txtRta.append("\n40 % nota 3: "+String.valueOf( ObjCLV.MR[ObjCLV.i][5]));
            
            txtRta.append("\nDefinitiva: "+String.valueOf(ObjCLV.MR[ObjCLV.i][6]));
            txtRta.append("\nMensaje por materia: "+( ObjCLV.MT[ObjCLV.i][1]));
            txtRta.append("\n........................................");
            
        }
        
        //Fin de todo el código para matrices
        
        ObjCLV.setMsj_definitivo(ObjML.CalcMsjDefinitivo(ObjCLV.getPerdidas()));
        txtRta.append("\n\n============================================");
        txtRta.append("\nTotal materias perdidas: "+String.valueOf(ObjCLV.getPerdidas()));
        txtRta.append("\nMensaje definitivo: "+(ObjCLV.getMsj_definitivo()));
        
    }//GEN-LAST:event_btn_libretaActionPerformed

