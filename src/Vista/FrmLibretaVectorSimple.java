    private void btn_libretaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_libretaActionPerformed
        // TODO add your handling code here:
        txtRta.append("LA ESCUELITA DE DOÑA RITA");
        txtRta.append("\nNombres: " + Nombres + " Apellidos: " + Apellidos);
        txtRta.append("\nGrado: " + Grado + " Director de grupo: " + Director);

        Cantidad = Integer.parseInt(JOptionPane.showInputDialog(null, "Cantidad de materias a procesar: ", "DATOS DE LA LIBRETA", JOptionPane.INFORMATION_MESSAGE));
        for (i = 1; i <= Cantidad; i++) { 
            //Limpieza
            v_materia[i] = "";
            v_nota1[i] = 0;
            v_nota2[i] = 0;
            v_nota3[i] = 0;
            v_nota1_30[i] = 0;
            v_nota2_30[i] = 0;
            v_nota3_40[i] = 0;
            v_definitiva[i] = 0;

            //Entrada de datos
            v_materia[i] = JOptionPane.showInputDialog(null, "Materia: ", "PROCESANDO REGISTRO: " + String.valueOf(i), JOptionPane.INFORMATION_MESSAGE);
                      
            //---------------------------------------
            //Filtro de la primera nota
            BandLetras = false;
            while (BandLetras!=true) {
                
                try {
                    /* El try verifica que se ingresen solo números.*/
                    Nota = Double.parseDouble(JOptionPane.showInputDialog(null, "Nota 1: ", "PROCESANDO REGISTRO: " 
                            + String.valueOf(i), JOptionPane.INFORMATION_MESSAGE));
                    /* Verifica que el valor de la nota este en el rango Nota>0 y Nota<=5
                             |(XXXXXXXXXXX]|
                    <--------|-------------|---------->
                    -∞      0             5        +∞ 
                
                     */
                    if ((Nota > 0) && (Nota <= 5)) {
                        /*
                    Si está en el rango, entonces la bandera BandLetras se 
                    vuelve verdadera.                    
                         */
                        BandLetras = true;

                    } else {
                        /*
                    En caso contrario, si no está en el rango, entonces la bandera BandLetras  
                    saca un mensaje de error y la bandera se vuelve falsa.
                      */
                        JOptionPane.showMessageDialog(null, "!Error!, nota fuera de rango."
                                + "\nSolo puede ingresar notas en el rango [Nota>0 y Nota<=5].",
                                "Entrada de datos inválida para nota.", JOptionPane.QUESTION_MESSAGE);

                        BandLetras = false;
                    }//Fin else

                } catch (NumberFormatException e) {

                    /*
                 El catch "atrapa" o "captura" el error y evita que el progama colapse.                               
                     */
                    //Despliega un mensaje de error
                    JOptionPane.showMessageDialog(null, "!Error!, en la lectura de la nota, solo puede ingresar números.\n" 
                            + e, "Entrada de datos inválida", JOptionPane.ERROR_MESSAGE);
                    //La bandera se vuelve falsa
                    BandLetras = false;

                }//Fin del filtro de lectura de la variable nota
            }//Fin while
            //Fin filtro de la primera nota.
            //---------------------------------------
            v_nota1[i] = Nota;//Una vez filtrada la nota, se le asigna al vector.
            //Continuar con el siguiente filtro
            v_nota2[i] = Double.parseDouble(JOptionPane.showInputDialog(null, "Nota 2: ", "PROCESANDO REGISTRO: " + String.valueOf(i), JOptionPane.INFORMATION_MESSAGE));
            v_nota3[i] = Double.parseDouble(JOptionPane.showInputDialog(null, "Nota 3: ", "PROCESANDO REGISTRO: " + String.valueOf(i), JOptionPane.INFORMATION_MESSAGE));
            //Cálculos
            v_nota1_30[i] = ObjML.Calc30(v_nota1[i]);
            v_nota2_30[i] = ObjML.Calc30(v_nota2[i]);
            v_nota3_40[i] = ObjML.Calc40(v_nota3[i]);
            v_definitiva[i] = ObjML.CalcDef(v_nota1_30[i], v_nota2_30[i], v_nota3_40[i]);

            if (v_definitiva[i] < 3) {
                perdidas++;//Cuenta la materia perdida.
            }
            v_msj_materia[i] = ObjML.CalcMsjMateria(v_definitiva[i]);

            //Impresión de resultados en el JTextArea
            txtRta.append("\nMateria: " + v_materia[i]);

            txtRta.append("\nNota 1: " + String.valueOf(v_nota1[i]));
            txtRta.append("\n30 % nota 1: " + String.valueOf(v_nota1_30[i]));

            txtRta.append("\nNota 2: " + String.valueOf(v_nota2[i]));
            txtRta.append("\n30 % nota 2: " + String.valueOf(v_nota2_30[i]));

            txtRta.append("\nNota 3: " + String.valueOf(v_nota3[i]));
            txtRta.append("\n40 % nota 3: " + String.valueOf(v_nota3_40[i]));

            txtRta.append("\nDefinitiva: " + String.valueOf(v_definitiva[i]));
            txtRta.append("\nMensaje por materia: " + (v_msj_materia[i]));
            txtRta.append("\n........................................");
            
            //Impresión de resultados en el JTable (Hoja de cálculo.
            //Inserta datos en la tabla
            ModeloNomina.insertRow(ModeloNomina.getRowCount(), new Object[]{v_materia[i], v_nota1[i], v_nota1_30[i], v_nota2[i],v_nota2_30[i], v_nota3[i],v_nota3_40[i],v_definitiva[i],v_msj_materia[i]});
            
        }

        msj_definitivo = ObjML.CalcMsjDefinitivo(perdidas);
        txtRta.append("\n\n============================================");
        txtRta.append("\nTotal materias perdidas: " + String.valueOf(perdidas));
        txtRta.append("\nMensaje definitivo: " + (msj_definitivo));


    }//GEN-LAST:event_btn_libretaActionPerformed


