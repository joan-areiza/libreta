    public void ReadFile() {
        //public void ReadFile() throws FileNotFoundException {     
        //Variables para lectura de archivo
        String filename;
        String file_with_extension;
        String Texto;

        // Get the filename.
        String nombre;

        filename = JOptionPane.showInputDialog("Ingrese el nombre del archivo (sin extensión):");
        file_with_extension = filename + ".txt";
        txtRta.setText(null);//Clean the text area

        // Open the file.
        try {
            File file = new File(file_with_extension);
            Scanner inputFile = null;
            inputFile = new Scanner(file);
            // Read lines from the file until no more are left.
            while (inputFile.hasNext()) {
                // Read the next line .
                String InfoLine = inputFile.nextLine();

                // Display the last info line read in the JTextAreaObject.
                txtRta.append(InfoLine + "\n");

            }

            // Close the file.
            inputFile.close();

        } catch (FileNotFoundException ex) {
            //Logger.getLogger(FrmLibretaFicheros.class.getName()).log(Level.SEVERE, null, ex);

            JOptionPane.showMessageDialog(null, "!Error!, " + "\nEl archivo solicitado no existe.\n" + ex, "Entrada de datos inválida", JOptionPane.ERROR_MESSAGE);
        }

    }//End method
