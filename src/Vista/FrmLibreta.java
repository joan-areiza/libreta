    private void btn_libretaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_libretaActionPerformed
        // TODO add your handling code here:
        txtRta.append("LA ESCUELITA DE DOÑA RITA");
        txtRta.append("\nNombres: "+ObjCL.getNombres()+" Apellidos: "+ObjCL.getApellidos());
        txtRta.append("\nGrado: "+ObjCL.getGrado()+" Director de grupo: "+ObjCL.getDirector());
        
        
        ObjCL.Cantidad = Integer.parseInt(JOptionPane.showInputDialog(null,"Cantidad de materias a procesar: ","DATOS DE LA LIBRETA",JOptionPane.INFORMATION_MESSAGE));
        for(ObjCL.i=1;ObjCL.i<=ObjCL.Cantidad;ObjCL.i++)
        {  //Entrada de datos
            ObjCL.setMateria(JOptionPane.showInputDialog(null,"Materia: ","PROCESANDO REGISTRO: "+String.valueOf(ObjCL.i),JOptionPane.INFORMATION_MESSAGE));
            ObjCL.setNota1(Double.parseDouble(JOptionPane.showInputDialog(null,"Nota 1: ","PROCESANDO REGISTRO: "+String.valueOf(ObjCL.i),JOptionPane.INFORMATION_MESSAGE)));
            ObjCL.setNota2(Double.parseDouble(JOptionPane.showInputDialog(null,"Nota 2: ","PROCESANDO REGISTRO: "+String.valueOf(ObjCL.i),JOptionPane.INFORMATION_MESSAGE)));
            ObjCL.setNota3(Double.parseDouble(JOptionPane.showInputDialog(null,"Nota 3: ","PROCESANDO REGISTRO: "+String.valueOf(ObjCL.i),JOptionPane.INFORMATION_MESSAGE)));
            //Cálculos
            ObjCL.setNota1_30(ObjML.Calc30(ObjCL.getNota1()));
            ObjCL.setNota2_30(ObjML.Calc30(ObjCL.getNota2()));
            ObjCL.setNota3_40(ObjML.Calc40(ObjCL.getNota3()));
            ObjCL.setDefinitiva(ObjML.CalcDef(ObjCL.getNota1_30(), ObjCL.getNota2_30(),ObjCL.getNota3_40()));
            
            if (ObjCL.getDefinitiva()<3) ObjCL.setPerdidas(ObjCL.getPerdidas()+1);//Cuenta la materia perdida.
            
            ObjCL.setMsj_materia(ObjML.CalcMsjMateria(ObjCL.getDefinitiva()));
            
            //Impresión de resultados
            txtRta.append("\nMateria: "+ObjCL.getMateria());
            
            txtRta.append("\nNota 1: "+String.valueOf(ObjCL.getNota1()));
            txtRta.append("\n30 % nota 1: "+String.valueOf(ObjCL.getNota1_30()));
            
            txtRta.append("\nNota 2: "+String.valueOf(ObjCL.getNota2()));
            txtRta.append("\n30 % nota 2: "+String.valueOf(ObjCL.getNota2_30()));
            
            txtRta.append("\nNota 3: "+String.valueOf(ObjCL.getNota3()));
            txtRta.append("\n40 % nota 3: "+String.valueOf(ObjCL.getNota3_40()));
            
            txtRta.append("\nDefinitiva: "+String.valueOf(ObjCL.getDefinitiva()));
            txtRta.append("\nMensaje por materia: "+(ObjCL.getMsj_materia()));
            txtRta.append("\n........................................");
            
        }
        
        ObjCL.setMsj_definitivo(ObjML.CalcMsjDefinitivo(ObjCL.getPerdidas()));
        txtRta.append("\n\n============================================");
        txtRta.append("\nTotal materias perdidas: "+String.valueOf(ObjCL.getPerdidas()));
        txtRta.append("\nMensaje definitivo: "+(ObjCL.getMsj_definitivo()));
        
    }//GEN-LAST:event_btn_libretaActionPerformed

